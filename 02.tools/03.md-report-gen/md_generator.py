# ────────────────────────────────────────
# ① Fail 케이스만 추출
# ────────────────────────────────────────
def Fail_추출(df):
    """
    전체 테스트 케이스에서 결과가 Fail 인 것만 추출
    """
    fail_df = df[df["결과"] == "Fail"].reset_index(drop=True)
    if len(fail_df) == 0:
        print("Fail 케이스가 없어요!")
        return None
    print(f"Fail 케이스: {len(fail_df)}건")
    return fail_df


# ────────────────────────────────────────
# ② 재현 절차 포맷팅
# ────────────────────────────────────────
def 재현절차_포맷(테스트단계):
    """
    테스트 단계 문자열을 마크다운 번호 목록으로 변환
    """
    if pd.isna(테스트단계) or str(테스트단계).strip() == "":
        return "1. \n2. \n3. "

    단계들 = str(테스트단계).strip().split("\n")
    결과 = []
    번호 = 1
    for 단계 in 단계들:
        단계 = 단계.strip().lstrip("0123456789. ")
        if 단계:
            결과.append(f"{번호}. {단계}")
            번호 += 1
    return "\n".join(결과) if 결과 else "1. \n2. \n3. "


# ────────────────────────────────────────
# ③ 마크다운 리포트 단일 생성
# ────────────────────────────────────────
def 마크다운_생성(버그ID, TC_ID, 행, 심각도기준_포함=True):
    """
    버그 하나의 마크다운 리포트 문자열 생성

    매개변수:
    - 버그ID         : 생성된 버그 ID
    - TC_ID          : 참조 테스트 케이스 ID
    - 행             : DataFrame 의 한 행
    - 심각도기준_포함: 심각도 기준표 포함 여부 (개별 파일 = True)
    """
    def 값(컬럼, 기본=""):
        try:
            v = 행.get(컬럼, 기본)
            return "" if pd.isna(v) else str(v).strip()
        except:
            return 기본

    제목      = 값("테스트명", "버그 제목")
    심각도    = 값("심각도",   "")
    우선순위  = 값("우선순위", "")
    발견자    = 값("발견자",   "")
    발견일    = 값("발견일",   datetime.now().strftime("%Y-%m-%d"))
    플랫폼    = 값("플랫폼",   "")
    버전      = 값("버전",     "")
    재현율    = 값("재현율",   "")
    테스트단계 = 값("테스트단계", "")
    예상결과  = 값("예상결과", "")
    실제결과  = 값("실제결과", "")
    분류      = 값("분류",     "")

    재현절차 = 재현절차_포맷(테스트단계)

    마크다운 = f"""## [{버그ID}] {제목}

| 항목 | 내용 |
|------|------|
| **심각도 (Severity)** | {심각도} |
| **우선순위 (Priority)** | {우선순위} |
| **테스트 케이스** | {TC_ID} |
| **분류** | {분류} |
| **발견 날짜** | {발견일} |
| **발견자** | {발견자} |
| **플랫폼** | {플랫폼} |
| **버전** | {버전} |
| **재현율** | {재현율} |

---

### 요약 (Summary)
> {제목}

### 재현 절차 (Steps to Reproduce)
{재현절차}

### 예상 결과 (Expected Result)
> {예상결과}

### 실제 결과 (Actual Result)
> {실제결과}

### 첨부 자료 (Attachments)
- 스크린샷:
- 동영상:
- 로그:

### 참고 사항 (Notes)
> 추가로 알아야 할 맥락, 연관 버그 등
"""

    # 심각도 기준 포함 여부 (개별 파일만 포함)
    if 심각도기준_포함:
        마크다운 += f"\n---\n{심각도기준}"

    return 마크다운


# ────────────────────────────────────────
# ④ 개별 .md 파일 저장
# ────────────────────────────────────────
def 개별_저장(버그ID, 마크다운내용):
    """
    버그 하나의 마크다운을 개별 파일로 저장
    저장 위치: 결과/bug_reports/BUG-001.md
    """
    저장폴더 = 기준경로 / "결과" / "bug_reports"
    저장폴더.mkdir(parents=True, exist_ok=True)

    파일명 = 저장폴더 / f"{버그ID}.md"
    with open(파일명, "w", encoding="utf-8") as f:
        f.write(마크다운내용)

    return 파일명


# ────────────────────────────────────────
# ⑤ 전체 통합 .md 파일 저장
# ────────────────────────────────────────
def 통합_저장(마크다운목록):
    """
    모든 버그 리포트를 하나의 파일로 통합 저장
    심각도 기준은 상단에 1번만 표시 (중복 방지)

    저장 위치: 결과/ALL_BUGS.md
    """
    결과폴더 = 결과폴더_생성(기준경로)
    시각 = 타임스탬프()
    파일명 = 결과폴더 / f"ALL_BUGS_{시각}.md"

    헤더 = f"""# 전체 버그 리포트

생성일: {시각} | 총 {len(마크다운목록)}건

---
{심각도기준}
---

"""

    with open(파일명, "w", encoding="utf-8") as f:
        f.write(헤더)
        f.write("\n\n---\n\n".join(마크다운목록))

    Latest_복사(파일명, "ALL_BUGS")
    return 파일명

# ────────────────────────────────────────
# ⑥ bugs.csv 저장 (excel-reporter 연동용)
# ────────────────────────────────────────
def bugs_csv_저장(fail_df, 버그ID목록):
    """
    Fail 케이스를 excel-reporter 입력 형식의 CSV로 저장
    저장 위치: 결과/bugs_YYYY-MM-DD.csv
    """
    결과폴더 = 결과폴더_생성(기준경로)

    시각   = 타임스탬프()
    파일명 = 결과폴더 / f"bugs_{시각}.csv"

    def 값_안전(행, 컬럼, 기본=""):
        try:
            v = 행.get(컬럼, 기본)
            return "" if pd.isna(v) else str(v).strip()
        except:
            return 기본

    헤더 = ["버그ID", "TC_ID", "제목", "심각도", "우선순위",
            "플랫폼", "버전", "상태", "발견자", "발견일", "해결일", "재현율"]

    with open(파일명, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(헤더)

        for i, (_, 행) in enumerate(fail_df.iterrows()):
            writer.writerow([
                버그ID목록[i],
                값_안전(행, "TC_ID"),
                값_안전(행, "테스트명"),
                값_안전(행, "심각도"),
                값_안전(행, "우선순위"),
                값_안전(행, "플랫폼"),
                값_안전(행, "버전"),
                "미해결",
                값_안전(행, "발견자"),
                값_안전(행, "발견일"),
                "",
                값_안전(행, "재현율"),
            ])
            
    Latest_복사(파일명, "bugs")
    return 파일명


# ────────────────────────────────────────
# ⑦ 전체 리포트 생성 (메인 함수)
# ────────────────────────────────────────
def 리포트_생성(파일명):
    """
    파일을 읽어서 마크다운 리포트 + bugs.csv 전체 생성

    매개변수:
    - 파일명: 분석할 CSV 또는 XLSX 파일 이름

    동작 순서:
    1. 파일 읽기 (CSV/XLSX 자동 판단) - common.file_io 사용
    2. Fail 케이스만 추출
    3. 버그 ID 순번 생성 (BUG-001 부터)
    4. 각 Fail 케이스마다 두 가지 마크다운 생성
       - 개별 파일용: 심각도 기준표 포함 (단독으로 봐도 의미 있게)
       - 통합 파일용: 심각도 기준표 미포함 (중복 방지)
    5. 통합 마크다운 파일 저장 (심각도 기준표는 상단에 1번만)
    6. bugs.csv 저장 (excel-reporter 입력용)

    반환값:
    - 딕셔너리:
        {
            "개별": [BUG-001.md 경로, BUG-002.md 경로, ...],
            "통합": ALL_BUGS.md 경로,
            "csv" : bugs_YYYY-MM-DD.csv 경로
        }
    - None: 파일 읽기 실패 또는 Fail 케이스 없을 때
    """
    # 1. 파일 읽기 (공통 모듈 사용)
    #    csv/xlsx 자동 판단, 인코딩 자동 처리
    df = 파일_읽기(파일명, 기준경로)
    if df is None:
        return None  # 파일 없음 / 지원 안 하는 형식

    # 2. Fail 케이스만 추출
    #    결과 컬럼이 "Fail" 인 행만 필터링
    fail_df = Fail_추출(df)
    if fail_df is None:
        return None  # Fail 케이스 없음

    # 3. 버그 ID 순번 생성 (BUG-001, BUG-002, ...)
    #    f-string의 :03d → 3자리 0 패딩 (001, 042, 999)
    버그ID목록 = [f"BUG-{i+1:03d}" for i in range(len(fail_df))]

    # 4. 개별 + 통합용 마크다운 동시 생성
    개별경로목록 = []   # 저장된 개별 .md 파일 경로 모음
    통합용목록 = []     # 통합 파일에 합칠 마크다운 문자열 모음

    for i, (_, 행) in enumerate(fail_df.iterrows()):
        버그ID = 버그ID목록[i]
        TC_ID  = str(행.get("TC_ID", "")).strip()  # 참조 TC ID

        # 4-1. 개별 파일용 마크다운 (심각도 기준표 포함)
        #      → 개별 .md 파일은 단독으로 봐도 기준을 알 수 있게
        개별마크다운 = 마크다운_생성(버그ID, TC_ID, 행, 심각도기준_포함=True)
        경로 = 개별_저장(버그ID, 개별마크다운)
        개별경로목록.append(경로)

        # 4-2. 통합 파일용 마크다운 (심각도 기준표 미포함)
        #      → 통합 파일에서는 상단에 한 번만 표시 (중복 방지)
        통합용마크다운 = 마크다운_생성(버그ID, TC_ID, 행, 심각도기준_포함=False)
        통합용목록.append(통합용마크다운)

        print(f"{버그ID} 생성 완료 (참조: {TC_ID})")

    # 5. 통합 마크다운 파일 저장
    #    통합_저장() 함수가 상단에 심각도 기준표를 1번 추가함
    통합경로 = 통합_저장(통합용목록)

    # 6. bugs.csv 저장 (excel-reporter 와 연동용)
    #    Fail 케이스를 버그 데이터 형식으로 변환해서 저장
    csv경로 = bugs_csv_저장(fail_df, 버그ID목록)

    # 결과 경로들을 딕셔너리로 묶어서 반환
    return {
        "개별": 개별경로목록,  # 개별 .md 파일들의 경로 리스트
        "통합": 통합경로,      # ALL_BUGS.md 경로
        "csv" : csv경로        # bugs_YYYY-MM-DD.csv 경로
    }