# ② 동등분할 TC 생성
# ────────────────────────────────────────
def 동등분할_TC_생성(사양):
    """
    동등 분할 기법으로 TC 생성
    유효/무효 입력값마다 TC 1개씩 생성

    매개변수:
    - 사양: JSON 사양 딕셔너리

    반환값:
    - TC 리스트 (딕셔너리 형태)
    """
    TC목록 = []
    동등분할 = 사양.get("동등분할", {})

    for 파라미터명, 값분류 in 동등분할.items():
        # 유효한 값들
        for 값 in 값분류.get("유효", []):
            TC목록.append({
                "기법": "동등분할",
                "테스트명": f"[동등분할] {파라미터명}: 유효값 '{값}' 입력",
                "파라미터": 파라미터명,
                "입력값": 값,
                "구분": "유효",
                "예상결과": f"{파라미터명}이(가) 정상 처리됨",
                "심각도": "Medium",
                "우선순위": "Medium"
            })
        # 무효한 값들
        for 값 in 값분류.get("무효", []):
            TC목록.append({
                "기법": "동등분할",
                "테스트명": f"[동등분할] {파라미터명}: 무효값 '{값}' 입력",
                "파라미터": 파라미터명,
                "입력값": 값,
                "구분": "무효",
                "예상결과": f"{파라미터명} 오류 메시지 표시",
                "심각도": "High",
                "우선순위": "Medium"
            })

    return TC목록


# ────────────────────────────────────────
# ③ 경계값 TC 생성
# ────────────────────────────────────────
def 경계값_TC_생성(사양):
    """
    경계값 분석 기법으로 TC 생성
    경계점 -1, 경계점, 경계점 +1 에서 TC 생성

    매개변수:
    - 사양: JSON 사양 딕셔너리

    반환값:
    - TC 리스트
    """
    TC목록 = []
    경계값 = 사양.get("경계값", {})

    for 파라미터명, 범위 in 경계값.items():
        최소 = 범위.get("최소")
        최대 = 범위.get("최대")
        단위 = 범위.get("단위", "")

        if 최소 is None or 최대 is None:
            continue

        # 경계 케이스: 최소-1, 최소, 최대, 최대+1
        경계점목록 = [
            (최소 - 1, "최소 미만", "오류 메시지 표시", "High"),
            (최소,      "최소값",    "정상 처리",        "Medium"),
            (최대,      "최대값",    "정상 처리",        "Medium"),
            (최대 + 1, "최대 초과", "오류 메시지 표시", "High"),
        ]

        for 값, 설명, 예상결과, 심각도 in 경계점목록:
            TC목록.append({
                "기법": "경계값",
                "테스트명": f"[경계값] {파라미터명} {설명}: {값}{단위}",
                "파라미터": 파라미터명,
                "입력값": f"{값}{단위}",
                "구분": 설명,
                "예상결과": 예상결과,
                "심각도": 심각도,
                "우선순위": "High"
            })

    return TC목록


# ────────────────────────────────────────
# ④ 결정테이블 TC 생성
# ────────────────────────────────────────
def 결정테이블_TC_생성(사양):
    """
    결정 테이블 기법으로 TC 생성
    조건 조합마다 TC 1개씩 생성

    매개변수:
    - 사양: JSON 사양 딕셔너리

    반환값:
    - TC 리스트
    """
    TC목록 = []
    결정테이블 = 사양.get("결정테이블", [])

    for 항목 in 결정테이블:
        조건 = 항목.get("조건", {})
        조건문자열 = ", ".join([f"{k}={v}" for k, v in 조건.items()])

        TC목록.append({
            "기법": "결정테이블",
            "테스트명": f"[결정테이블] {조건문자열}",
            "파라미터": " + ".join(조건.keys()),
            "입력값": 조건문자열,
            "구분": "조합",
            "예상결과": 항목.get("예상결과", ""),
            "심각도": 항목.get("심각도", "Medium"),
            "우선순위": 항목.get("우선순위", "Medium")
        })

    return TC목록


# ────────────────────────────────────────
# ⑤ 재현 절차 포맷팅
# ────────────────────────────────────────
def 재현절차_포맷(공통헤더, 테스트액션):
    """
    공통 헤더 + 테스트별 액션을 마크다운 번호 목록으로 변환

    매개변수:
    - 공통헤더 : 공통 재현 절차 (리스트)
    - 테스트액션: 이 TC의 마지막 액션 (문자열)

    반환값:
    - 번호가 매겨진 절차 문자열
    """
    전체 = list(공통헤더) + [테스트액션]
    return "\n".join([f"{i+1}. {단계}" for i, 단계 in enumerate(전체)])


# ────────────────────────────────────────
# ⑥ TC → testcases.csv 변환
# ────────────────────────────────────────
def CSV_저장(사양, TC목록):
    """
    TC 목록을 testcases.csv 형식으로 저장
    03.md-report-gen / 02.data-validator 와 호환

    매개변수:
    - 사양     : JSON 사양 딕셔너리
    - TC목록   : 전체 TC 리스트

    저장 위치: 결과/testcases_{기능명}_{타임스탬프}.csv
    """
    결과폴더 = 결과폴더_생성(기준경로)

    기능명 = 사양.get("기능명", "unknown")
    분류   = 사양.get("분류", "")
    전제조건 = 사양.get("전제조건", "")
    공통헤더 = 사양.get("공통_재현절차_헤더", [])

    시각 = 타임스탬프()
    파일명 = 결과폴더 / f"testcases_{기능명}_{시각}.csv"

    헤더 = [
        "TC_ID", "테스트명", "분류", "전제조건",
        "테스트단계", "예상결과", "실제결과", "결과",
        "심각도", "우선순위", "플랫폼", "발견자", "발견일", "기법"
    ]

    with open(파일명, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(헤더)

        for i, TC in enumerate(TC목록, 1):
            테스트액션 = f"{TC['파라미터']} 에 '{TC['입력값']}' 입력 후 동작 수행"
            재현절차 = 재현절차_포맷(공통헤더, 테스트액션)

            writer.writerow([
                f"TC-{i:03d}",
                TC["테스트명"],
                분류,
                전제조건,
                재현절차,
                TC["예상결과"],
                "",                           # 실제결과 (비워둠)
                "",                           # 결과 (실행 후 입력)
                TC["심각도"],
                TC["우선순위"],
                "PC",                         # 기본 플랫폼
                "자동생성",                    # 발견자
                datetime.now().strftime("%Y-%m-%d"),
                TC["기법"]                    # 추가 컬럼
            ])

    Latest_복사(파일명, f"testcases_{기능명}")
    log.info(f"CSV 저장 완료: {파일명} ({len(TC목록)}건)")
    return 파일명


