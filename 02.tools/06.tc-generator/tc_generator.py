# ⑦ 전체 TC 생성 (메인)
# ────────────────────────────────────────
def 전체_TC_생성(사양파일):
    """
    사양 파일 하나로부터 전체 TC를 자동 생성

    매개변수:
    - 사양파일: JSON 사양 파일 경로

    동작 순서:
    1. 사양 파일 로딩
    2. 동등분할 TC 생성
    3. 경계값 TC 생성
    4. 결정테이블 TC 생성
    5. testcases.csv 저장

    반환값:
    - 딕셔너리: {"파일": 경로, "건수": int, "기법별": {...}}
    """
    # 1. 사양 로딩
    사양 = 사양_로딩(사양파일)
    if 사양 is None:
        return None

    기능명 = 사양.get("기능명", "unknown")
    log.info(f"TC 생성 시작: {기능명}")

    # 2. 각 기법으로 TC 생성
    동등분할_TC = 동등분할_TC_생성(사양)
    경계값_TC   = 경계값_TC_생성(사양)
    결정테이블_TC = 결정테이블_TC_생성(사양)

    전체 = 동등분할_TC + 경계값_TC + 결정테이블_TC

    # 3. CSV 저장
    저장경로 = CSV_저장(사양, 전체)

    결과 = {
        "파일": 저장경로,
        "건수": len(전체),
        "기법별": {
            "동등분할": len(동등분할_TC),
            "경계값"  : len(경계값_TC),
            "결정테이블": len(결정테이블_TC)
        }
    }

    log.info(f"TC 생성 완료: {기능명} ({len(전체)}건)")
    return 결과


def 전체_사양_TC_생성():
    """
    specs/ 폴더의 모든 JSON 파일로부터 TC를 자동 생성

    반환값:
    - 결과 리스트
    """
    specs폴더 = 기준경로 / "specs"
    if not specs폴더.exists():
        log.error(f"specs 폴더 없음: {specs폴더}")
        return []

    JSON목록 = list(specs폴더.glob("*.json"))
    if not JSON목록:
        log.warning(f"specs 폴더에 JSON 파일 없음")
        return []

    log.info(f"전체 사양 처리 시작: {len(JSON목록)}개")
    결과목록 = []
    for 사양파일 in JSON목록:
        결과 = 전체_TC_생성(사양파일)
        if 결과:
            결과목록.append(결과)

    log.info(f"전체 사양 처리 완료: {len(결과목록)}건")
    return 결과목록